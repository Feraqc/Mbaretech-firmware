invalid(r=>r.initialState='MISSING',/inicial/);
invalid(r=>r.states[1].id=r.states[0].id,/único/);
invalid(r=>r.states[0].id='MISSING',/no existe/);
invalid(r=>r.states[0].motion='MISSING',/MotionId/);
invalid(r=>r.states[0].left=101,/rango/);
invalid(r=>r.states[0].transitions[0].target='MISSING',/destino/);
invalid(r=>r.states[1].transitions[0].terms=['MISSING'],/ConditionId/);
invalid(r=>r.states[1].transitions[0].operators=[],/operadores/);
invalid(r=>r.states[1].steps=[],/pasos/);
