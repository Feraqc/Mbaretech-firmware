fs.writeFileSync(path.join(build,'validate.cpp'),'#include <cassert>\n#include "fsm/StateMachine.h"\n#include "roundtrip.h"\n#include "fresh.h"\nint main(){assert(!fsm::validateRecipe(fsm_recipe_turn_calibration::MACHINE));assert(!fsm::validateRecipe(fsm_recipe_editor_test::MACHINE));}\n');
